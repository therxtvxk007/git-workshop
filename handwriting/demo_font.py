"""A built-in single-stroke font.

This is *not* anybody's handwriting — it exists so the pipeline can be tested,
demoed and calibrated before you have captured your own.  Once you have run
``hwm capture``, use your own font file instead; that is the entire point of
the machine.

Coordinates: baseline y=0, y-up, x-height 5, cap height 7, ascender 7.5,
descender -2.5, em 10.
"""

