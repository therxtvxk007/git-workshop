def build(name: str = "reference-hand") -> Font:
    """Construct the built-in font."""
    font = Font(
        name=name,
        metrics=Metrics(
            em=10.0, x_height=5.0, cap_height=7.0,
            ascender=7.5, descender=-2.5, space_advance=2.6,
        ),
    )
    for char, (strokes, advance) in _GLYPHS.items():
        entry = strokes[0][0] if strokes and strokes[0] else None
        exit_ = strokes[-1][-1] if strokes and strokes[-1] else None
        font.add(char, Variant([list(s) for s in strokes], advance, entry, exit_))
    return font
