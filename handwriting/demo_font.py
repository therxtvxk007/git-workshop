X = 5.0    # x-height
CAP = 7.0  # cap height


def L(*points: tuple[float, float]) -> Stroke:
    """A polyline through the given points."""
    return [(float(x), float(y)) for x, y in points]


def A(cx: float, cy: float, rx: float, ry: float, a0: float, a1: float) -> Stroke:
    """An elliptical arc from ``a0`` to ``a1`` degrees (counter-clockwise if
    ``a1 > a0``), sampled finely enough to look smooth at writing size."""
    sweep = abs(a1 - a0)
    steps = max(6, int(sweep / 12))
    pts: Stroke = []
    for i in range(steps + 1):
        ang = math.radians(a0 + (a1 - a0) * i / steps)
        pts.append((cx + rx * math.cos(ang), cy + ry * math.sin(ang)))
    return pts


def O(cx: float, cy: float, rx: float, ry: float | None = None) -> Stroke:
    """A closed ellipse."""
    return A(cx, cy, rx, ry if ry is not None else rx, 0, 360)


def dot(x: float, y: float, r: float = 0.28) -> Stroke:
    return O(x, y, r)


